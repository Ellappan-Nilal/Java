import java.util.*;
public class Swap {
    public static void main(String[] args){
        Scanner sc=new Scanner(System.in);
        String n1=sc.next();
        String n2=sc.next();
        String temp;
        temp=n1;
        n1=n2;
        n2=temp;
        System.out.print(n1);
        System.out.print(n2);
        
      
    }
}
